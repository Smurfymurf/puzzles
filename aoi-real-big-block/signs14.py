import os, sys
D = os.path.expanduser("~/puzzles/aoi-real-big-block")
sys.path.insert(0, D)
import aoi
aoi._init()
P = aoi._S["paras"]; n = len(P)
def fL(p): return next((c for c in p if c.isalpha()), "?")
def lL(p): return next((c for c in reversed(p) if c.isalpha()), "?")
F = "".join(fL(p) for p in P)
L = "".join(lL(p) for p in P)
print("=== CHAPTER first letters (273) ===")
for i in range(0, n, 60): print(f"{i:3d} {F[i:i+60]}")
print("=== CHAPTER last letters (273) ===")
for i in range(0, n, 60): print(f"{i:3d} {L[i:i+60]}")
print("first letters vowels    :", "".join(c for c in F if c.lower() in "aeiou"))
print("first letters consonants:", "".join(c for c in F if c.isalpha() and c.lower() not in "aeiou"))
print("last letters vowels     :", "".join(c for c in L if c.lower() in "aeiou"))
print("last letters consonants :", "".join(c for c in L if c.isalpha() and c.lower() not in "aeiou"))
print("flip mask (1=flip):", "".join("1" if fL(p).upper() not in "ITSAM" else "0" for p in P))
print()
